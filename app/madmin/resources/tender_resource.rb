class TenderResource < Madmin::Resource
  # 5.6M rows / 21GB: keep the index narrow, never LIKE-search text columns
  # (Madmin's default search is a full scan; see Madmin::TendersController for
  # exact-match lookup), and only sort on indexed columns.
  INDEX = { index: true }.freeze
  DETAIL = { index: false }.freeze
  TEXT = { index: false, searchable: false }.freeze

  attribute :id, form: false
  attribute :tender_id, **INDEX, searchable: false
  attribute :title, **INDEX, searchable: false
  attribute :organisation, **INDEX, searchable: false
  attribute :state, **INDEX, searchable: false
  attribute :tender_source, **INDEX, searchable: false
  attribute :submission_close_date, **INDEX
  attribute :is_visible, **INDEX

  attribute :description, **TEXT
  attribute :short_blog, **TEXT
  attribute :tender_value, **DETAIL
  attribute :tender_fee, **DETAIL
  attribute :emd, **DETAIL
  attribute :bid_open_date, **DETAIL
  attribute :submission_open_date, **DETAIL
  attribute :tender_reference_number, **TEXT
  attribute :tender_category, **TEXT
  attribute :tender_contract_type, **TEXT
  attribute :location, **TEXT
  attribute :page_link, **TEXT
  attribute :slug, **TEXT
  attribute :slug_uuid, **TEXT
  attribute :bid_result_status, **TEXT
  attribute :bid_result_updated_at, **DETAIL
  attribute :meta_data, index: false, form: false
  attribute :full_data, index: false, form: false, searchable: false
  attribute :created_at, index: false, form: false
  attribute :updated_at, index: false, form: false
  attribute :updated_at_auto, index: false, form: false
  # Generated by Postgres (tender_text_vector, text_search_trigram) or internal:
  # never shown or written.

  attribute :attachments, index: false
  attribute :bookmarks, index: false

  def self.display_name(record) = record.title.to_s.truncate(80)

  def self.default_sort_column = 'id'
  def self.default_sort_direction = 'desc'

  def self.sortable_columns = %w[id submission_close_date updated_at_auto state tender_source]
end
